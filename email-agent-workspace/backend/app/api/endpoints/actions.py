"""
API Endpoints for Actions: Draft Management, Approval, Sending, and Clarification Responses.
"""
import logging
from datetime import datetime
from typing import Optional, List
from fastapi import APIRouter, Depends, HTTPException, Query, BackgroundTasks
from sqlalchemy.orm import Session
from app.core.database import get_db, SessionLocal
from app.db.models import DraftModel, ClarificationRequestModel
from app.schemas.response import (
    DraftCreate, DraftResponse, ClarificationReply, ClarificationResponse
)
from app.adapters.outlook_mail import outlook_mail_client

logger = logging.getLogger(__name__)

router = APIRouter()

# ---- Drafts Endpoints ----

@router.get("/drafts", response_model=List[DraftResponse])
def list_drafts(
    status: Optional[str] = Query(None, description="Filter by draft status: staged, approved, sent"),
    email_id: Optional[int] = Query(None),
    db: Session = Depends(get_db)
):
    """Lists drafts with optional status filtering."""
    query = db.query(DraftModel)
    if status:
        query = query.filter(DraftModel.status == status)
    if email_id:
        query = query.filter(DraftModel.email_id == email_id)
    return query.order_by(DraftModel.created_at.desc()).all()


@router.post("/compose", response_model=DraftResponse, status_code=201)
def compose_draft(draft_in: DraftCreate, db: Session = Depends(get_db)):
    """Manually creates or stages a response draft."""
    draft = DraftModel(
        email_id=draft_in.email_id,
        recipient=draft_in.recipient,
        subject=draft_in.subject,
        body=draft_in.body,
        tone=draft_in.tone,
        status="staged"
    )
    db.add(draft)
    db.commit()
    db.refresh(draft)
    return draft


@router.post("/drafts/{draft_id}/approve", response_model=DraftResponse)
def approve_draft(draft_id: int, db: Session = Depends(get_db)):
    """Approves a staged draft for dispatch."""
    draft = db.query(DraftModel).filter(DraftModel.id == draft_id).first()
    if not draft:
        raise HTTPException(status_code=404, detail="Draft not found")

    draft.status = "approved"
    draft.approved_at = datetime.utcnow()
    db.commit()
    db.refresh(draft)
    return draft


@router.post("/drafts/{draft_id}/send", response_model=DraftResponse)
def send_draft(draft_id: int, db: Session = Depends(get_db)):
    """Dispatches the approved draft via Outlook Mail adapter."""
    draft = db.query(DraftModel).filter(DraftModel.id == draft_id).first()
    if not draft:
        raise HTTPException(status_code=404, detail="Draft not found")

    success = outlook_mail_client.send_email(
        to=draft.recipient,
        subject=draft.subject,
        body=draft.body
    )
    if not success:
        raise HTTPException(status_code=500, detail="Failed to dispatch email via Outlook service.")

    draft.status = "sent"
    draft.sent_at = datetime.utcnow()
    db.commit()
    db.refresh(draft)
    return draft


# ---- Clarifications Endpoints ----

@router.get("/clarifications", response_model=List[ClarificationResponse])
def list_clarifications(
    status: Optional[str] = Query(None, description="Filter by status: pending, resolved"),
    email_id: Optional[int] = Query(None),
    db: Session = Depends(get_db)
):
    """Retrieves clarification requests generated by the Supervisor Agent."""
    query = db.query(ClarificationRequestModel)
    if status:
        query = query.filter(ClarificationRequestModel.status == status)
    if email_id:
        query = query.filter(ClarificationRequestModel.email_id == email_id)
    return query.order_by(ClarificationRequestModel.created_at.desc()).all()


async def _resume_workflow_async(email_id: int, resolved_context: str):
    """Asynchronously resumes the orchestrator pipeline with the resolved clarification context."""
    from app.agents.orchestrator import orchestrator
    with SessionLocal() as session:
        try:
            logger.info(f"Autonomously resuming orchestrator pipeline for Email #{email_id}...")
            await orchestrator.process_email(
                email_id=email_id,
                db=session,
                resolved_context=resolved_context
            )
            logger.info(f"Autonomous resumption completed for Email #{email_id}.")
        except Exception as e:
            logger.error(f"Error resuming workflow after clarification: {e}")


@router.post("/clarifications/{clarification_id}/reply", response_model=ClarificationResponse)
async def answer_clarification(
    clarification_id: int,
    reply: ClarificationReply,
    background_tasks: BackgroundTasks,
    db: Session = Depends(get_db)
):
    """
    Submits user clarification answer, resolving the workflow pause,
    and autonomously resumes the orchestrator pipeline.
    """
    clarification = db.query(ClarificationRequestModel).filter(ClarificationRequestModel.id == clarification_id).first()
    if not clarification:
        raise HTTPException(status_code=404, detail="Clarification request not found")

    clarification.status = "resolved"
    clarification.resolution = reply.answer
    db.commit()
    db.refresh(clarification)

    # Autonomous Resume: trigger orchestrator with the clarified context
    if clarification.email_id:
        background_tasks.add_task(_resume_workflow_async, clarification.email_id, reply.answer)

    return clarification
